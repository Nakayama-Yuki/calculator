#!/usr/bin/env python3
"""独立したWebアプリのCIを共通テンプレートから生成する。"""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[3]
APPS = {
    "PomodoroTimer": ("node.js.yml", "Node.js CI(pnpm)", "build"),
    "calculator": ("node.js.yml", "Node.js CI(pnpm)", "build"),
    "chatapp6": ("node.js.yml", "Node.js CI(pnpm)", "build"),
    "ec-product-list2": ("nodejs.ci.yml", "nodejs.ci(pnpm)", "build"),
    "recipe-search2": ("node.js.yml", "Node.js CI(pnpm)", "build"),
    "tic-tac-toe": ("nodejs.yml", "nodejs.ci(pnpm)", "test"),
    "todoapp": ("node.js.yml", "Node.js CI(pnpm)", "buildAndtest"),
    "todoapp-rr": ("node.js.yml", "Node.js CI(pnpm)", "buildAndTest"),
    "weatherapp": ("playwright.yml", "nodejs.ci(pnpm)", "test"),
    "weatherapp-rr": ("node.js.yml", "Node.js CI(pnpm)", "buildAndTypecheck"),
}
MOCKED = {"chatapp6", "ec-product-list2", "recipe-search2", "weatherapp"}


def live_api_workflow(app):
    urls = {
        "ec-product-list2": "https://fakestoreapi.com/products",
        "weatherapp": "https://api.openweathermap.org/data/2.5/weather?q=Tokyo&units=metric",
        "recipe-search2": "https://api.spoonacular.com/recipes/complexSearch?query=pasta&number=1",
    }
    key = ""
    if app == "weatherapp":
        key = "          API_KEY: ${{ secrets.OPENWEATHER_API_KEY }}\n"
    elif app == "recipe-search2":
        key = "          API_KEY: ${{ secrets.SPOONACULAR_API_KEY }}\n"
    parameter = "appid" if app == "weatherapp" else "apiKey"
    validation = {
        "ec-product-list2": "Array.isArray(data) && data.length > 0 && typeof data[0].id === 'number'",
        "weatherapp": "typeof data.name === 'string' && typeof data.main?.temp === 'number'",
        "recipe-search2": "Array.isArray(data.results) && typeof data.totalResults === 'number'",
    }[app]
    return f"""# Generated by calculator/tools/web-ci/generate.py.
name: Live API smoke test

on:
  workflow_dispatch:

permissions:
  contents: read

jobs:
  live-api:
    runs-on: ubuntu-latest
    timeout-minutes: 5
    steps:
      - uses: actions/checkout@v7
      - uses: pnpm/setup@v3
        with:
          runtime: node@lts
          install: false
      - name: Check external API response
        env:
          API_URL: {urls[app]}
{key}        run: |
          node --input-type=module <<'JS'
          const url = new URL(process.env.API_URL);
          if (url.hostname !== 'fakestoreapi.com') {{
            if (!process.env.API_KEY) throw new Error('Configure the API key secret before running this workflow');
            url.searchParams.set('{parameter}', process.env.API_KEY);
          }}
          const response = await fetch(url, {{ signal: AbortSignal.timeout(15000) }});
          if (!response.ok) throw new Error(`API returned HTTP ${{response.status}}`);
          const data = await response.json();
          if (!({validation})) throw new Error('Unexpected API response schema');
          console.log('Live API response schema verified');
          JS
"""


def workflow(app, name, job):
    db = app in {"todoapp", "todoapp-rr"}
    node = "24" if app == "tic-tac-toe" else "lts"
    text = f"""# Generated by calculator/tools/web-ci/generate.py.
name: {name}

on:
  push:
    branches: [main]
  pull_request:
    branches: [main]
  workflow_dispatch:

permissions:
  contents: read

concurrency:
  group: ci-${{{{ github.workflow }}}}-${{{{ github.ref }}}}
  cancel-in-progress: true

jobs:
  {job}:
    runs-on: ubuntu-latest
    timeout-minutes: 30
"""
    if db:
        text += """    env:
      PGHOST: localhost
      PGPORT: 5432
      PGUSER: ci_user
      PGPASSWORD: ci_password
      PGDATABASE: ci_test
"""
        if app == "todoapp":
            text += """      DATABASE_URL: postgresql://ci_user:ci_password@localhost:5432/ci_test
      AUTH_SECRET: github-actions-test-secret
      AUTH_TRUST_HOST: "true"
"""
        else:
            text += """      DATABASE_HOST: localhost
      DATABASE_PORT: 5432
      DATABASE_USER: ci_user
      DATABASE_PASSWORD: ci_password
      DATABASE_NAME: ci_test
"""
        major = "18" if app == "todoapp" else "17"
        text += f"""
    services:
      postgres:
        image: postgres:{major}-alpine
        env:
          POSTGRES_DB: ci_test
          POSTGRES_USER: ci_user
          POSTGRES_PASSWORD: ci_password
        options: >-
          --health-cmd "pg_isready -U ci_user -d ci_test"
          --health-interval 10s
          --health-timeout 5s
          --health-retries 5
        ports:
          - 5432:5432
"""
    text += f"""
    steps:
      - uses: actions/checkout@v7

      - name: Setup pnpm, Node.js and dependencies
        uses: pnpm/setup@v3
        with:
          runtime: node@{node}
          cache: true
          require-lockfile: true

      - name: Type and lint checks
        run: pnpm ci:check
"""
    if db:
        text += """
      - name: Initialize isolated test database
        run: psql -v ON_ERROR_STOP=1 -f init.sql
"""
    if app == "todoapp":
        text += """
      - name: Verify non-destructive database initialization
        run: pnpm test:db
"""
    if not app.endswith("-rr"):
        text += f"""
      - name: Cache Next.js build
        uses: actions/cache@v6
        with:
          path: .next/cache
          key: ${{{{ runner.os }}}}-node-{node}-nextjs-${{{{ hashFiles('pnpm-lock.yaml') }}}}-${{{{ hashFiles('src/**', 'app/**', 'components/**', 'lib/**', 'utils/**', 'tests/**', 'public/**', '*config*') }}}}
          restore-keys: |
            ${{{{ runner.os }}}}-node-{node}-nextjs-${{{{ hashFiles('pnpm-lock.yaml') }}}}-
"""
    command = "build:e2e" if app in MOCKED else "build"
    text += f"""
      - name: Build production application
        run: pnpm {command}
"""
    if app == "chatapp6":
        text += """        env:
          NEXT_PUBLIC_SUPABASE_URL: http://127.0.0.1:54321
          NEXT_PUBLIC_SUPABASE_ANON_KEY: e2e-only-key
"""
    browsers = "" if app == "tic-tac-toe" else " chromium"
    text += f"""
      - name: Install Playwright browsers
        run: pnpm exec playwright install --with-deps{browsers}

      - name: Test production application
        run: pnpm test:e2e

"""
    if app == "todoapp":
        text += """      - name: Verify ownership and database failure recovery
        run: pnpm test:security

"""
    text += """      - name: Upload Playwright reports
        uses: actions/upload-artifact@v7
        if: ${{ !cancelled() }}
        with:
          name: playwright-report
          path: |
            playwright-report/
            playwright-security-report/
          retention-days: 30
          if-no-files-found: ignore
"""
    return text


def docker_workflow(app):
    text = """# Generated by calculator/tools/web-ci/generate.py.
name: Docker CI

on:
  push:
    branches: [main]
    paths: [Dockerfile, .dockerignore, .npmrc, init.sql, package.json, pnpm-lock.yaml, pnpm-workspace.yaml, 'app/**', 'src/**', 'public/**', '*config*', '.github/workflows/docker.yml']
  pull_request:
    branches: [main]
    paths: [Dockerfile, .dockerignore, .npmrc, init.sql, package.json, pnpm-lock.yaml, pnpm-workspace.yaml, 'app/**', 'src/**', 'public/**', '*config*', '.github/workflows/docker.yml']
  workflow_dispatch:

permissions:
  contents: read

concurrency:
  group: docker-${{ github.workflow }}-${{ github.ref }}
  cancel-in-progress: true

jobs:
  docker:
    runs-on: ubuntu-latest
    timeout-minutes: 20
    steps:
      - uses: actions/checkout@v7
      - name: Build production image
        run: docker build --tag web-app-ci .
      - name: Verify runtime starts
        run: |
          docker run --detach --name web-app-ci -p 3000:3000 \\
            -e DATABASE_URL=postgresql://ci_user:ci_password@127.0.0.1:5432/ci_test \\
            -e DATABASE_HOST=127.0.0.1 -e DATABASE_PORT=5432 \\
            -e DATABASE_USER=ci_user -e DATABASE_PASSWORD=ci_password -e DATABASE_NAME=ci_test \\
            -e AUTH_SECRET=github-actions-test-secret web-app-ci
          for attempt in $(seq 1 30); do
            if curl --silent --fail http://localhost:3000/ >/dev/null; then exit 0; fi
            if [ "$(docker inspect -f '{{.State.Running}}' web-app-ci)" != true ]; then break; fi
            sleep 2
          done
          docker logs web-app-ci
          exit 1
      - name: Clean up
        if: ${{ always() }}
        run: docker rm --force web-app-ci || true
"""


    if app in {"todoapp", "todoapp-rr"}:
        major = "18" if app == "todoapp" else "17"
        service = f"""    services:
      postgres:
        image: postgres:{major}-alpine
        env:
          POSTGRES_DB: ci_test
          POSTGRES_USER: ci_user
          POSTGRES_PASSWORD: ci_password
        ports:
          - 5432:5432
        options: >-
          --health-cmd "pg_isready -U ci_user -d ci_test"
          --health-interval 10s
          --health-timeout 5s
          --health-retries 5
"""
        text = text.replace("    steps:", service + "    steps:")
        text = text.replace("      - name: Build production image", """      - name: Initialize test database
        run: docker exec -i "${{ job.services.postgres.id }}" psql -U ci_user -d ci_test -v ON_ERROR_STOP=1 < init.sql
      - name: Build production image""")
        text = text.replace("--name web-app-ci -p 3000:3000", "--name web-app-ci --add-host host.docker.internal:host-gateway -p 3000:3000")
        text = text.replace("127.0.0.1", "host.docker.internal")
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="生成結果との差分だけを検査")
    parser.add_argument("--root", type=Path, default=ROOT, help="アプリを配置した親ディレクトリ")
    parser.add_argument("--app", choices=APPS, help="単一アプリだけを生成・検査")
    args = parser.parse_args()
    root = args.root.resolve()
    selected = {args.app: APPS[args.app]} if args.app else APPS
    for app in selected:
        if not (root / app / ".github" / "workflows").is_dir():
            parser.error(f"Repository not found: {root / app}; use --root or --app")
    mismatches = []
    for app, (filename, name, job) in selected.items():
        files = {filename: workflow(app, name, job)}
        if app in {"ec-product-list2", "weatherapp", "recipe-search2"}:
            files["live-api.yml"] = live_api_workflow(app)
        if app in {"todoapp", "todoapp-rr", "weatherapp-rr"}:
            files["docker.yml"] = docker_workflow(app)
        for filename, contents in files.items():
            path = root / app / ".github" / "workflows" / filename
            if args.check:
                if not path.exists() or path.read_text() != contents:
                    mismatches.append(str(path.relative_to(root)))
            else:
                path.write_text(contents)
    if mismatches:
        raise SystemExit("Regenerate workflows: " + ", ".join(mismatches))
    print("CI templates verified" if args.check else f"Generated CI for {len(selected)} apps")


if __name__ == "__main__":
    main()
